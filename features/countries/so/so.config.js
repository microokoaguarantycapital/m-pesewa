// CONFIGURATION VALIDATION
// ============================================
const validateSomaliaConfig = () => {
    const errors = [];
    
    // Hierarchy validation
    if (!SomaliaConfig.hierarchy.structure.country.isolation.enabled) {
        errors.push('Country isolation MUST be enabled for Somalia');
    }
    
    // Currency validation
    if (SomaliaConfig.currency.code !== 'SOS') {
        errors.push('Currency MUST be SOS for Somalia');
    }
    
    // Subscription validation
    if (SomaliaConfig.subscriptions.borrowerTiers.basic.cost !== 0) {
        errors.push('Borrowers MUST have zero subscription cost');
    }
    
    // Loan rules validation
    if (SomaliaConfig.loans.general.interestRate !== 10) {
        errors.push('Interest rate MUST be 10%');
    }
    
    if (errors.length > 0) {
        console.error('❌ Somalia Configuration Validation Failed:');
        errors.forEach(error => console.error(`  - ${error}`));
        throw new Error('Somalia configuration invalid');
    }
    
    console.log('✅ Somalia Configuration Validated Successfully');
    return true;
};

// ============================================
// HIERARCHY ENFORCEMENT FUNCTIONS
// ============================================
const SomaliaHierarchy = {
    /**
     * Validate user belongs to Somalia
     * @param {Object} user - User object
     * @returns {boolean} - True if user is in Somalia
     */
    validateCountry: (user) => {
        if (!user || !user.country) return false;
        return user.country.toUpperCase() === 'SO';
    },
    
    /**
     * Enforce group isolation
     * @param {string} lenderGroupId - Lender's group ID
     * @param {string} borrowerGroupId - Borrower's group ID
     * @returns {boolean} - True if lending allowed
     */
    validateGroupIsolation: (lenderGroupId, borrowerGroupId) => {
        return lenderGroupId === borrowerGroupId;
    },
    
    /**
     * Check if user can join more groups
     * @param {Object} user - User object
     * @param {number} currentGroups - Current groups count
     * @returns {boolean} - True if can join more
     */
    canJoinMoreGroups: (user, currentGroups) => {
        if (user.role === 'borrower') {
            return currentGroups < SomaliaConfig.hierarchy.structure.groups.limits.maxGroupsPerUser;
        }
        return true; // Lenders have no group limit
    },
    
    /**
     * Validate subscription status for lender
     * @param {Object} lender - Lender object
     * @returns {Object} - Validation result
     */
    validateLenderSubscription: (lender) => {
        const today = new Date();
        const expiryDate = new Date(lender.subscription.expiry);
        
        return {
            isValid: today <= expiryDate,
            daysRemaining: Math.ceil((expiryDate - today) / (1000 * 60 * 60 * 24)),
            expiryDay: expiryDate.getDate(),
            isExpiryMonth: today.getDate() === 28 && today.getMonth() === expiryDate.getMonth()
        };
    }
};

