const SomaliaUtils = {
    /**
     * Format currency for Somalia
     * @param {number} amount - Amount in SOS
     * @returns {string} - Formatted currency
     */
    formatCurrency: (amount) => {
        return `S ${amount.toLocaleString('en-SO')}`;
    },
    
    /**
     * Calculate loan repayment
     * @param {number} principal - Loan amount
     * @param {number} days - Days overdue (0-7 normal, >7 penalty)
     * @returns {Object} - Repayment details
     */
    calculateRepayment: (principal, days = 7) => {
        const interest = principal * 0.10; // 10% interest
        let penalty = 0;
        
        if (days > 7) {
            const overdueDays = days - 7;
            penalty = principal * 0.05 * overdueDays; // 5% daily penalty
        }
        
        const total = principal + interest + penalty;
        
        return {
            principal,
            interest,
            penalty,
            total,
            breakdown: {
                dailyRepayment: total / 7,
                weeklyTotal: total,
                penaltyStarts: days > 7 ? 'Day 8' : 'No penalty'
            }
        };
    },
    
    /**
     * Validate Somali phone number
     * @param {string} phone - Phone number
     * @returns {boolean} - True if valid
     */
    validatePhone: (phone) => {
        const regex = SomaliaConfig.validation.phoneNumber.regex;
        return regex.test(phone);
    },
    
    /**
     * Get tier limits for lender
     * @param {string} tier - Subscription tier
     * @returns {Object} - Tier limits
     */
    getTierLimits: (tier) => {
        const tiers = SomaliaConfig.subscriptions.lenderTiers;
        return tiers[tier] || tiers.basic;
    }
};

