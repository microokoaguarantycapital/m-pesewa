    // Loan Operations
    calculateLoan(amount, days = 7) {
        const interest = amount * this.ledgers.interestRate;
        const totalRepayment = amount + interest;
        
        let penalty = 0;
        if (days > 7) {
            const extraDays = days - 7;
            penalty = amount * this.ledgers.penaltyRate * extraDays;
        }
        
        return {
            principal: amount,
            interest: interest,
            total: totalRepayment + penalty,
            dailyRepayment: (totalRepayment + penalty) / days,
            breakdown: {
                principal: amount,
                interest: interest,
                penalty: penalty,
                total: totalRepayment + penalty
            }
        };
    }
    
    // Subscription Operations
    checkSubscriptionStatus() {
        if (!this.state.subscription || !this.state.user) {
            return { active: false, message: 'No subscription found' };
        }
        
        const today = new Date();
        const expiryDate = this.calculateSubscriptionExpiry();
        
        const isActive = today <= expiryDate;
        const daysRemaining = Math.ceil((expiryDate - today) / (1000 * 60 * 60 * 24));
        
        return {
            active: isActive,
            expiryDate: expiryDate,
            daysRemaining: daysRemaining,
            tier: this.state.subscription,
            limits: this.subscriptions[this.state.subscription]
        };
    }
    
    calculateSubscriptionExpiry() {
        const today = new Date();
        const currentMonth = today.getMonth();
        const currentYear = today.getFullYear();
        
        // Subscription expires on 28th of each month
        let expiryDate = new Date(currentYear, currentMonth, 28);
        
        // If today is past the 28th, set to 28th of next month
        if (today.getDate() > 28) {
            expiryDate = new Date(currentYear, currentMonth + 1, 28);
        }
        
        return expiryDate;
    }
    
    // Validation Methods
    validateBorrowerForLoan(borrowerId, amount, groupId) {
        const borrower = this.getUserById(borrowerId);
        if (!borrower) {
            return { valid: false, error: 'Borrower not found' };
        }
        
        if (borrower.isBlacklisted) {
            return { valid: false, error: 'Borrower is blacklisted' };
        }
        
        if (borrower.rating < 3) {
            return { valid: false, error: 'Borrower rating too low' };
        }
        
        // Check if borrower is in the group
        if (!borrower.groups.includes(groupId)) {
            return { valid: false, error: 'Borrower not in specified group' };
        }
        
        // Check active loans in this group
        const activeLoans = this.getActiveLoans(borrowerId, groupId);
        if (activeLoans.length > 0) {
            return { valid: false, error: 'Borrower has active loan in this group' };
        }
        
        return { valid: true, borrower };
    }
    
    validateLenderForLoan(lenderId, amount, subscriptionTier) {
        const lender = this.getUserById(lenderId);
        if (!lender) {
            return { valid: false, error: 'Lender not found' };
        }
        
        const subscription = this.checkSubscriptionStatus();
        if (!subscription.active) {
            return { valid: false, error: 'Lender subscription expired' };
        }
        
        const tierLimit = this.subscriptions[subscriptionTier]?.maxPerWeek || 0;
        if (amount > tierLimit) {
            return { valid: false, error: `Amount exceeds tier limit (${tierLimit})` };
        }
        
        return { valid: true, lender, subscription };
    }
    
