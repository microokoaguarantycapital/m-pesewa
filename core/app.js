    // User Operations
    registerUser(userData) {
        const { role, country, group, subscription } = userData;
        
        // Validate country
        if (!this.countries[country]) {
            throw new Error(`Invalid country: ${country}`);
        }
        
        // Validate role
        if (!['lender', 'borrower', 'both'].includes(role)) {
            throw new Error('Role must be lender, borrower, or both');
        }
        
        // Validate subscription for lenders
        if (role === 'lender' || role === 'both') {
            if (!subscription) {
                throw new Error('Lenders must select a subscription tier');
            }
            if (!this.subscriptions[subscription]) {
                throw new Error(`Invalid subscription tier: ${subscription}`);
            }
        }
        
        const user = {
            id: `user_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
            ...userData,
            registrationDate: new Date(),
            rating: 5,
            status: 'active',
            isBlacklisted: false,
            groups: [],
            ledgers: []
        };
        
        this.state.user = user;
        this.state.isAuthenticated = true;
        this.state.role = role;
        this.state.country = country;
        
        if (role === 'lender' || role === 'both') {
            this.state.isLender = true;
            this.state.subscription = subscription;
        }
        
        if (role === 'borrower' || role === 'both') {
            this.state.isBorrower = true;
        }
        
        // Store in localStorage
        localStorage.setItem('mpesewa_user', JSON.stringify(user));
        localStorage.setItem('mpesewa_auth', 'true');
        
        console.log(`User registered: ${userData.username} as ${role} in ${country}`);
        return user;
    }
    
