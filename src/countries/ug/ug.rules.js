export function performComplianceCheck(entity, operation) {
    const rules = getUgandaRules();
    const checks = [];
    
    // Check country isolation
    checks.push({
        check: 'COUNTRY_ISOLATION',
        passed: entity.country === 'UG',
        message: entity.country === 'UG' ? 
            'Country isolation maintained' : 
            'Cross-country operation attempted'
    });
    
    // Check hierarchy compliance
    const hierarchyCheck = rules.validateHierarchy(entity);
    checks.push({
        check: 'HIERARCHY_COMPLIANCE',
        passed: hierarchyCheck.isValid,
        message: hierarchyCheck.isValid ? 
            'Hierarchy rules followed' : 
            hierarchyCheck.errors[0]
    });
    
    // Check legal compliance
    checks.push({
        check: 'LEGAL_COMPLIANCE',
        passed: true, // Assume passed, actual check would be more complex
        message: 'Compliant with Uganda regulations'
    });
    
    // Check subscription if lender
    if (entity.type === 'lender' && operation === 'lend') {
        const subscriptionCheck = rules.validateLenderSubscription(entity, entity.subscription);
        checks.push({
            check: 'SUBSCRIPTION_VALID',
            passed: subscriptionCheck.canLend,
            message: subscriptionCheck.canLend ? 
                'Active subscription' : 
                'Subscription expired or invalid'
        });
    }
    
    const allPassed = checks.every(c => c.passed);
    
    return {
        compliant: allPassed,
        checks,
        entityType: entity.type,
        operation,
        timestamp: new Date().toISOString()
    };
}

