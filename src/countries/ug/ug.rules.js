    validateHierarchy(entity) {
        const errors = [];
        
        // Ensure country isolation
        if (entity.country !== this.countryCode) {
            errors.push(`Entity country ${entity.country} does not match Uganda (UG)`);
        }
        
        // Group validation
        if (entity.type === 'group') {
            if (!entity.members || entity.members.length < this.hierarchy.groups.minMembers) {
                errors.push(`Group must have at least ${this.hierarchy.groups.minMembers} members`);
            }
            
            if (entity.members && entity.members.length > this.hierarchy.groups.maxMembers) {
                errors.push(`Group cannot exceed ${this.hierarchy.groups.maxMembers} members`);
            }
        }
        
        // Lender validation
        if (entity.type === 'lender') {
            if (!entity.subscription) {
                errors.push('Lender must have active subscription');
            }
            
            if (entity.subscription && entity.subscription.country !== this.countryCode) {
                errors.push('Lender subscription must be for Uganda');
            }
        }
        
        // Borrower validation
        if (entity.type === 'borrower') {
            if (entity.blacklisted) {
                errors.push('Blacklisted borrowers cannot participate');
            }
            
            if (entity.groups && entity.groups.length > this.hierarchy.groups.maxGroupsPerUser) {
                errors.push(`Borrower cannot join more than ${this.hierarchy.groups.maxGroupsPerUser} groups`);
            }
        }
        
        return {
            isValid: errors.length === 0,
            errors,
            hierarchy: this.hierarchy
        };
    }

